-- ---------------------------------------------------------------------
-- 统一视图
-- ---------------------------------------------------------------------
DROP VIEW IF EXISTS v_orders_base;
CREATE VIEW v_orders_base AS
SELECT
  o.order_id,
  o.customer_id,
  c.customer_unique_id,
  c.customer_state,
  o.order_status,
  o.order_purchase_timestamp                        AS purchase_ts,
  to_char(o.order_purchase_timestamp, 'YYYY-MM')    AS ym,
  o.order_delivered_customer_date                   AS delivered_ts,
  o.order_estimated_delivery_date                   AS estimated_ts,
  pay.pay_value,
  it.gmv,
  it.item_cnt
FROM orders o
JOIN customers c
  ON c.customer_id = o.customer_id
LEFT JOIN (
  SELECT order_id, SUM(payment_value) AS pay_value
  FROM order_payments GROUP BY order_id
) pay ON pay.order_id = o.order_id
LEFT JOIN (
  SELECT order_id, SUM(price) AS gmv, COUNT(*) AS item_cnt
  FROM order_items GROUP BY order_id
) it ON it.order_id = o.order_id
WHERE o.order_status NOT IN ('canceled', 'unavailable');

-- ---------------------------------------------------------------------
-- 指标 1：月度 GMV / 订单量 / AOV / 环比
-- ---------------------------------------------------------------------
WITH m AS (
  SELECT ym,
         SUM(gmv)                           AS gmv,
         COUNT(DISTINCT order_id)           AS order_cnt,
         COUNT(DISTINCT customer_unique_id) AS buyer_cnt
  FROM v_orders_base
  WHERE gmv IS NOT NULL
    AND ym BETWEEN '2017-01' AND '2018-08'
  GROUP BY ym
)
SELECT ym,
       ROUND(gmv, 2)                        AS gmv,
       order_cnt,
       buyer_cnt,
       ROUND(gmv / NULLIF(order_cnt, 0), 2) AS aov,
       ROUND((gmv - LAG(gmv) OVER (ORDER BY ym))
             / NULLIF(LAG(gmv) OVER (ORDER BY ym), 0) * 100, 2) AS gmv_mom_pct
FROM m
ORDER BY ym;

-- ---------------------------------------------------------------------
-- 指标 2：复购率
-- 注意 SUM(order_cnt >= 2) 在 PG 里会报错，必须 ::int 转成 0/1 再求和
-- ---------------------------------------------------------------------
WITH oc AS (
  SELECT customer_unique_id,
         COUNT(DISTINCT order_id) AS order_cnt,
         SUM(gmv)                 AS gmv
  FROM v_orders_base
  WHERE gmv IS NOT NULL
  GROUP BY customer_unique_id
)
SELECT COUNT(*)                                                       AS buyer_cnt,
       SUM((order_cnt >= 2)::int)                                     AS repeat_buyer_cnt,
       ROUND(SUM((order_cnt >= 2)::int)::numeric / COUNT(*) * 100, 2) AS repeat_rate_pct,
       ROUND(AVG(order_cnt)::numeric, 2)                              AS avg_orders_per_buyer,
       ROUND(SUM(CASE WHEN order_cnt >= 2 THEN gmv ELSE 0 END)
             / NULLIF(SUM(gmv), 0) * 100, 2)                          AS repeat_gmv_share_pct
FROM oc;

-- ---------------------------------------------------------------------
-- 指标 3：次月留存（cohort）
-- PG 的月份加减比 MySQL 简单：date_trunc + interval
-- ---------------------------------------------------------------------
WITH first_buy AS (
  SELECT customer_unique_id,
         to_char(MIN(purchase_ts), 'YYYY-MM') AS cohort_ym
  FROM v_orders_base
  WHERE gmv IS NOT NULL
  GROUP BY customer_unique_id
),
act AS (
  SELECT DISTINCT customer_unique_id, ym
  FROM v_orders_base
  WHERE gmv IS NOT NULL
)
SELECT f.cohort_ym,
       COUNT(DISTINCT f.customer_unique_id) AS cohort_size,
       COUNT(DISTINCT CASE
         WHEN a.ym = to_char(date_trunc('month', to_date(f.cohort_ym || '-01', 'YYYY-MM-DD'))
                             + interval '1 month', 'YYYY-MM')
         THEN a.customer_unique_id END)     AS m1_retained,
       ROUND(COUNT(DISTINCT CASE
         WHEN a.ym = to_char(date_trunc('month', to_date(f.cohort_ym || '-01', 'YYYY-MM-DD'))
                             + interval '1 month', 'YYYY-MM')
         THEN a.customer_unique_id END)::numeric
         / NULLIF(COUNT(DISTINCT f.customer_unique_id), 0) * 100, 2) AS m1_retention_pct
FROM first_buy f
LEFT JOIN act a
  ON a.customer_unique_id = f.customer_unique_id
WHERE f.cohort_ym BETWEEN '2017-01' AND '2018-07'
GROUP BY f.cohort_ym
ORDER BY f.cohort_ym;

-- ---------------------------------------------------------------------
-- 指标 4：订单状态转化率
-- ---------------------------------------------------------------------
SELECT COUNT(*)                                                              AS placed_orders,
       SUM((order_approved_at IS NOT NULL)::int)                             AS paid_orders,
       SUM((order_delivered_customer_date IS NOT NULL)::int)                 AS delivered_orders,
       ROUND(SUM((order_approved_at IS NOT NULL)::int)::numeric / COUNT(*) * 100, 2) AS pay_rate_pct,
       ROUND(SUM((order_delivered_customer_date IS NOT NULL)::int)::numeric
             / NULLIF(SUM((order_approved_at IS NOT NULL)::int), 0) * 100, 2) AS deliver_rate_pct
FROM orders;

-- ---------------------------------------------------------------------
-- 指标 5：品类 GMV 占比 + 累计占比
-- ---------------------------------------------------------------------
WITH cat AS (
  SELECT COALESCE(t.product_category_name_english, p.product_category_name, 'unknown') AS category,
         SUM(oi.price)               AS gmv,
         COUNT(DISTINCT oi.order_id) AS order_cnt,
         ROUND(AVG(oi.price), 2)     AS avg_price
  FROM order_items oi
  JOIN orders o
    ON o.order_id = oi.order_id
   AND o.order_status NOT IN ('canceled', 'unavailable')
  JOIN products p
    ON p.product_id = oi.product_id
  LEFT JOIN product_category_name_translation t
    ON t.product_category_name = p.product_category_name
  GROUP BY COALESCE(t.product_category_name_english, p.product_category_name, 'unknown')
)
SELECT category,
       ROUND(gmv, 2)                                          AS gmv,
       order_cnt,
       avg_price,
       ROUND(gmv / SUM(gmv) OVER () * 100, 2)                  AS gmv_share_pct,
       ROUND(SUM(gmv) OVER (ORDER BY gmv DESC
                            ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW)
             / SUM(gmv) OVER () * 100, 2)                      AS cum_share_pct
FROM cat
ORDER BY gmv DESC;

-- ---------------------------------------------------------------------
-- 指标 6：RFM（R×M 二维）
-- PG 里两个 date 相减直接得到整数天数
-- ---------------------------------------------------------------------
WITH base AS (
  SELECT customer_unique_id,
         (SELECT MAX(purchase_ts)::date FROM v_orders_base) - MAX(purchase_ts)::date AS recency_days,
         COUNT(DISTINCT order_id) AS frequency,
         SUM(gmv)                 AS monetary
  FROM v_orders_base
  WHERE gmv IS NOT NULL
  GROUP BY customer_unique_id
),
scored AS (
  SELECT *,
         NTILE(5) OVER (ORDER BY recency_days ASC) AS r_score,
         NTILE(5) OVER (ORDER BY frequency ASC)    AS f_score,
         NTILE(5) OVER (ORDER BY monetary ASC)     AS m_score
  FROM base
)
SELECT r_score,
       m_score,
       COUNT(*)                 AS customer_cnt,
       ROUND(SUM(monetary), 2)  AS gmv,
       ROUND(AVG(monetary), 2)  AS avg_monetary,
       ROUND(AVG(frequency), 2) AS avg_frequency,
       CASE
         WHEN r_score >= 4 AND m_score >= 4 THEN '重要价值'
         WHEN r_score >= 4 AND m_score <  4 THEN '新客/潜力'
         WHEN r_score <  4 AND m_score >= 4 THEN '重要挽留'
         ELSE '流失/低价值'
       END AS segment
FROM scored
GROUP BY r_score, m_score
ORDER BY gmv DESC;

-- ---------------------------------------------------------------------
-- 指标 7：配送延迟 vs 差评率
-- ---------------------------------------------------------------------
SELECT CASE
         WHEN delay_days <= 0  THEN '1_准时或提前'
         WHEN delay_days <= 7  THEN '2_延迟1-7天'
         WHEN delay_days <= 14 THEN '3_延迟8-14天'
         ELSE                       '4_延迟14天以上'
       END                                        AS delay_bucket,
       COUNT(*)                                   AS order_cnt,
       ROUND(AVG(review_score), 2)                AS avg_score,
       ROUND(AVG((review_score <= 2)::int) * 100, 2) AS bad_review_pct
FROM (
  SELECT o.order_id,
         o.order_delivered_customer_date::date - o.order_estimated_delivery_date::date AS delay_days,
         r.review_score
  FROM orders o
  JOIN order_reviews r ON r.order_id = o.order_id
  WHERE o.order_delivered_customer_date IS NOT NULL
    AND o.order_estimated_delivery_date IS NOT NULL
    AND r.review_score IS NOT NULL
) t
GROUP BY delay_bucket
ORDER BY delay_bucket;
